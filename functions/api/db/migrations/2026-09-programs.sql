-- Programs module (events/recitals/kutcheris) + participant roster.
-- Run this against the live Supabase Postgres before the Programs module goes
-- live. Idempotent (create table if not exists).

create table if not exists programs (
  id            bigint generated by default as identity primary key,
  org_id        bigint not null,
  name          text not null,
  type          text default 'other',              -- recital|workshop|competition|kutchery|other
  program_date  text,                              -- YYYY-MM-DD
  description   text default '',
  fee           numeric default 0,
  status        text default 'planned',            -- planned|completed|cancelled
  source_id     bigint,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz
);
create index if not exists idx_programs_org on programs (org_id);

create table if not exists programstudents (
  id          bigint generated by default as identity primary key,
  org_id      bigint not null,
  program_id  bigint not null,
  student_id  bigint not null,
  billed      integer default 0,
  source_id   bigint,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz
);
create index if not exists idx_programstudents_org on programstudents (org_id);
create index if not exists idx_programstudents_program on programstudents (program_id);
create index if not exists idx_programstudents_student on programstudents (student_id);
